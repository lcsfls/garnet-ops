/** The country codes a home location can name, sorted. */
export const COUNTRY_CODES: readonly string[] = Object.keys(CAPITALS).sort();

export const isCountryCode = (value: unknown): value is string =>
  typeof value === "string" && Object.hasOwn(CAPITALS, value);

/** The capital of a country as a point, or null for a code the table does not have. */
export function capitalOf(code: string): { name: string; lat: number; lon: number } | null {
  if (!Object.hasOwn(CAPITALS, code)) return null;
  const [name, lat, lon] = CAPITALS[code] as CapitalEntry;
  return { name, lat, lon };
}
