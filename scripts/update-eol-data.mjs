#!/usr/bin/env node
/**
 * Refreshes packages/core/src/eol-data.ts, the snapshot of end-of-life dates the website checks judge software versions with
 * (ADR 0038). Run it before a release; the product works offline with the committed snapshot.
 *
 *   node scripts/update-eol-data.mjs
 *
 * Source: the product pages of endoflife.date (MIT License, https://github.com/endoflife-date/endoflife.date), read from GitHub.
 * Only the release cycles, their end of life and their latest version are kept.
 */
import { writeFileSync } from "node:fs";

const PRODUCTS = [
  "php",
  "wordpress",
  "nginx",
  "apache-http-server",
  "drupal",
  "joomla",
  "typo3",
  "mediawiki",
  "nextcloud",
  "magento",
  "shopware",
  "tomcat",
  "nodejs",
];
const BASE = "https://raw.githubusercontent.com/endoflife-date/endoflife.date/master/products";

/** The `releases:` list of a product page's front matter: releaseCycle, eol (a date, true or false) and latest. */
function parseReleases(markdown) {
  const front = markdown.split(/^---$/m)[1] ?? "";
  const block = front.split(/^releases:\s*$/m)[1] ?? "";
  const cycles = [];
  let current = null;
  for (const line of block.split("\n")) {
    if (/^\S/.test(line)) break; // the next top-level key
    const item = /^\s*-\s+releaseCycle:\s*"?([^"\s]+)"?/.exec(line);
    if (item) {
      current = { cycle: item[1], eol: null, latest: null };
      cycles.push(current);
      continue;
    }
    const field = /^\s+(eol|latest):\s*"?([^"#]*?)"?\s*(#.*)?$/.exec(line);
    if (current && field) {
      const value = field[2].trim();
      if (field[1] === "latest") current.latest = value || null;
      else
        current.eol =
          value === "true"
            ? true
            : value === "false"
              ? false
              : /^\d{4}-\d{2}-\d{2}$/.test(value)
                ? value
                : null;
    }
  }
  return cycles.filter((c) => c.eol !== null);
}

const products = {};
for (const product of PRODUCTS) {
  const res = await fetch(`${BASE}/${product}.md`);
  if (!res.ok) throw new Error(`${product}: HTTP ${res.status}`);
  const cycles = parseReleases(await res.text());
  if (cycles.length === 0) throw new Error(`${product}: no release cycles found`);
  products[product] = cycles;
}

const today = new Date().toISOString().slice(0, 10);
writeFileSync(
  new URL("../packages/core/src/eol-data.ts", import.meta.url),
  `// Generated by scripts/update-eol-data.mjs on ${today}. Do not edit by hand.
// Source: endoflife.date (https://github.com/endoflife-date/endoflife.date), MIT License, © endoflife.date contributors.

/** One release cycle: when it stops getting fixes (a date, or true/false when the project names none) and its latest version. */
export interface EolCycle {
  cycle: string;
  eol: string | boolean;
  latest: string | null;
}

export const EOL_DATA_DATE = ${JSON.stringify(today)};

export const EOL_DATA: Record<string, EolCycle[]> = ${JSON.stringify(products, null, 2)};
`,
);
console.log(`eol-data: ${PRODUCTS.length} products, as of ${today}`);
