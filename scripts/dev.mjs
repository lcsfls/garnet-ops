#!/usr/bin/env node
/**
 * Local development without Docker:
 *  - starts an embedded PostgreSQL in .data/pg,
 *  - creates development secrets once (.data/dev.env, .data/vault/*),
 *  - runs API, worker and web together with prefixed output.
 *
 * Development only. Production uses the Docker Compose stack with real secrets.
 */
import { spawn } from "node:child_process";
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { chmodSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import EmbeddedPostgres from "embedded-postgres";
import {
  clearStalePostgresLock,
  devPidFile,
  PG_PORT,
  pgDataDir,
  portInUse,
  runningPostgresPid,
  stopTree,
} from "./dev-lib.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const data = join(root, ".data");
const vaultDir = join(data, "vault");
const envFile = join(data, "dev.env");
const exe = process.platform === "win32" ? ".exe" : "";

mkdirSync(vaultDir, { recursive: true });

const pub = join(vaultDir, "vault.pub.pem");
const priv = join(vaultDir, "vault.key.pem");

/** Hybrid vault key (X25519 + ML-KEM-1024), same layout as generateVaultKeyPair() in packages/core/src/vault.ts. */
function writeVaultKey() {
  const x = generateKeyPairSync("x25519");
  const k = generateKeyPairSync("ml-kem-1024");
  const pem = (key, type) => key.export({ type, format: "pem" });
  writeFileSync(pub, pem(x.publicKey, "spki") + pem(k.publicKey, "spki"));
  writeFileSync(priv, pem(x.privateKey, "pkcs8") + pem(k.privateKey, "pkcs8"), { mode: 0o600 });
  chmodSync(priv, 0o600);
}

// Development keys from before the hybrid vault hold only X25519; replace them.
if (existsSync(pub) && (readFileSync(pub, "utf8").match(/BEGIN PUBLIC KEY/g) ?? []).length < 2) {
  writeVaultKey();
  console.log("dev: replaced the development vault key with a hybrid X25519 + ML-KEM-1024 key;");
  console.log("dev: secrets stored with the old key can no longer be opened, add those repositories again");
}

if (!existsSync(envFile)) {
  writeVaultKey();
  const pgPassword = randomBytes(18).toString("base64url");
  writeFileSync(join(data, "pg-password"), pgPassword, { mode: 0o600 });
  const lines = [
    "# Generated by scripts/dev.mjs for local development. Never use in production.",
    "NODE_ENV=development",
    "PUBLIC_URL=http://localhost:5173",
    "PORT=3000",
    `DATABASE_URL=postgres://garnetops:${pgPassword}@127.0.0.1:${PG_PORT}/garnetops`,
    `BETTER_AUTH_SECRET=${randomBytes(32).toString("base64url")}`,
    `GARNETOPS_VAULT_PUBLIC_KEY_FILE=${pub}`,
    `GARNETOPS_VAULT_PRIVATE_KEY_FILE=${priv}`,
    `GARNETOPS_GRYPE_BIN=${join(root, ".tools", "grype", `grype${exe}`)}`,
    `GARNETOPS_GRYPE_DB_DIR=${join(root, ".tools", "grype-db")}`,
    `GARNETOPS_SYFT_BIN=${join(root, ".tools", "syft", `syft${exe}`)}`,
    `GARNETOPS_WORK_DIR=${join(data, "work")}`,
  ];
  writeFileSync(envFile, `${lines.join("\n")}\n`, { mode: 0o600 });
  console.log("dev: created .data/dev.env and a development vault key");
}

const env = Object.fromEntries(
  readFileSync(envFile, "utf8")
    .split("\n")
    .filter((l) => l && !l.startsWith("#"))
    .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]),
);
// Added after the first dev.env files were written; fill in for existing ones.
env.GARNETOPS_SYFT_BIN ??= join(root, ".tools", "syft", `syft${exe}`);
const pgPassword = new URL(env.DATABASE_URL).password;

const pg = new EmbeddedPostgres({
  databaseDir: pgDataDir,
  user: "garnetops",
  password: pgPassword,
  port: PG_PORT,
  persistent: true,
  onLog: () => {},
  onError: (e) => console.error("[pg]", String(e).trim()),
});

// Reuse a development PostgreSQL that is still running (e.g. after a crash);
// only a server this run started is stopped again on exit.
let startedPostgres = false;
const runningPg = await runningPostgresPid();
if (!runningPg && (await clearStalePostgresLock())) {
  console.log("dev: removed a stale PostgreSQL lock file left by a crash");
}
if (runningPg) {
  console.log(`dev: reusing the running development PostgreSQL (pid ${runningPg})`);
} else if (await portInUse(PG_PORT)) {
  console.error(`dev: port ${PG_PORT} is used by another program; stop it and try again`);
  process.exit(1);
} else if (!existsSync(join(pgDataDir, "PG_VERSION"))) {
  await pg.initialise();
  await pg.start();
  await pg.createDatabase("garnetops");
  startedPostgres = true;
} else {
  await pg.start();
  startedPostgres = true;
}
console.log(`dev: postgres on 127.0.0.1:${PG_PORT}`);

for (const port of [3000, 5173]) {
  if (await portInUse(port)) {
    console.error(
      `dev: port ${port} is in use. If an earlier \`pnpm dev\` is still running, run \`pnpm dev:stop\` first.`,
    );
    if (startedPostgres) await pg.stop().catch(() => {});
    process.exit(1);
  }
}

if (!existsSync(env.GARNETOPS_GRYPE_BIN)) {
  console.log("dev: grype missing, run `pnpm scanners:fetch -- --with-db` first");
}

writeFileSync(devPidFile, String(process.pid));

const colours = { api: "\x1b[36m", worker: "\x1b[35m", web: "\x1b[33m" };
const children = [];
for (const [name, filter] of [
  ["api", "@garnetops/api"],
  ["worker", "@garnetops/worker"],
  ["web", "@garnetops/web"],
]) {
  // Windows needs a shell to run corepack's .cmd shim; Node 24 deprecates passing an argument
  // list together with a shell, so the (constant) command is one string there.
  const isWindows = process.platform === "win32";
  const command = isWindows ? `corepack pnpm --filter ${filter} dev` : "corepack";
  const args = isWindows ? [] : ["pnpm", "--filter", filter, "dev"];
  const child = spawn(command, args, {
    cwd: root,
    env: { ...process.env, ...env },
    shell: isWindows,
    // Own process group on Unix, so stopping it reaches every process it started.
    detached: process.platform !== "win32",
    stdio: ["ignore", "pipe", "pipe"],
  });
  const prefix = `${colours[name]}[${name}]\x1b[0m `;
  const pipe = (stream, out) => {
    let buf = "";
    stream.on("data", (d) => {
      buf += d.toString();
      const lines = buf.split("\n");
      buf = lines.pop() ?? "";
      for (const line of lines) out.write(`${prefix}${line}\n`);
    });
  };
  pipe(child.stdout, process.stdout);
  pipe(child.stderr, process.stderr);
  children.push(child);
}

let stopping = false;
async function stop() {
  if (stopping) return;
  stopping = true;
  // Whole trees: on Windows, killing the shell alone would leave API, worker and Vite running.
  for (const child of children) if (child.pid) stopTree(child.pid);
  if (startedPostgres) await pg.stop().catch(() => {});
  rmSync(devPidFile, { force: true });
  process.exit(0);
}
process.on("SIGINT", stop);
process.on("SIGTERM", stop);
